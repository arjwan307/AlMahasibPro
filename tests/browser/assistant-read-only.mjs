 assert.equal(await page.locator('.assistant-report button').filter({hasText:'أضف'}).count(),0);
 const downloadPromise=page.waitForEvent('download');await report.getByText('تنزيل CSV',{exact:true}).click();
 const download=await downloadPromise;assert.ok(download.suggestedFilename().endsWith('.csv'));
 const popupPromise=page.waitForEvent('popup');await report.getByText('طباعة التقرير',{exact:true}).click();
 const popup=await popupPromise;await popup.waitForLoadState();assert.match(await popup.locator('body').innerText(),/SA-1/);await popup.close();
